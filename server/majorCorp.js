// 한글 키워드가 다른 단어 안에 우연히 들어있는 경우를 막는다(예: "굿네이버스" 안의 "네이버").
// 키워드 바로 앞 글자가 한글이면 다른 단어의 일부로 보고 매칭하지 않는다(문자열 시작이면 통과).
function hasBoundary(text, keyword) {
  const idx = text.indexOf(keyword);
  if (idx < 0) return false;
  if (idx === 0) return true;
  return !/[가-힣]/.test(text[idx - 1]);
}

export function isMajorCorp(org) {
  const t = org || "";
  return MAJOR_CORPS.some((c) => hasBoundary(t, c));
}
